          <td><h4>Construction</h4>
            <ul>
              <li>Carefully chamfer (bevel) the inside edge of the xxx&quot; PVC pipe on the end that will be glued into the 1-1/4&quot; adapter. (This is the aft end of the pipe.) The schedule-80 nipple will be forced into this pipe-end, and the chamfer is vital to later assembly steps. This can be done with a common utility knife or jack-knife. </li>
              <li>Glue together as shown in the photo. </li>
            </ul></td>
          <td><?php thumbnailreference("dscn2419", 2); ?></td>
        </tr>
        <tr>
          <td><h4>Construction (cont.)</h4>
            <ul>
              <li>Drill a hole or holes through the centering ring. The wires for the dump solenoid valve must come through this centering ring.</li>
              <li>On the outside of the brass cap mark where the threads begin.</li>
              <li>On the 1/2&quot; schedule 80 pipe, place a mark on the pipe where the threads begin.</li>
              <li>Coat the threads on both the cap and the nipple-end with high-temperature grease (McMaster Carr part# xxxx). Screw the brass end cap onto the nipple <em>exactly</em> five turns. </li>
              <li>Chamfer the outside edge of the cut end of the schedule-80 nipple.</li>
              <li>Coat the outside of the schedule-80 nipple with PVC primer. Coat should extend from the cut edge about 1-1/2&quot; toward the brass cap. Wait for the primer to mostly dry, then scrape it off with a utility knife. Repeat 2 or 3 times to reduce the outer diameter of the nipple slightly. </li>
              <li>Coat the nipple with primer one last time, then working quickly, set the brass flat on the floor and the primed nipple, brass-cap down, onto the brass flat. Set the aft assembly onto the nipple. Using a sledge hammer pound the fitting onto the nipple until the fitting is flat on the floor. Hold firmlyuntil the glue sets. </li>
              <li>Place the centering ring on the  short length of 3/4. Glue the two assemblies together to finish the tank aft fitting. </li>
              <li>When complete the afted face of the brass end cap should be just slightly recessed. </li>
            </ul></td>
