      <p>If you have not already done so, review the <a href="tankforward.php" target="Glue">notes on gluing PVC pipe</a>. </p>
      <h3>AFT Tank Closure / Injector Nipple / Injector </h3>
      <p>All parts are described with words and McMaster-Carr part numbers. I do not recommend purchasing PVC parts on-line. They should be available from your local Home Depot or Lowes. </p>
      <h4>Note:</h4>
      <p>This assembly involves the only precision work in the entire process. Read the directions carefully and completely before begining.</p>
      <p>The problem with this design is that this piece will form two seals. The pyrovalve will mate with the injector and the chamber will mate with the aft threads on this fitting. Both seals must be gas tight but not over tightned when the chamber is screwed on. Forming two seals with one fitting (the chamber) requires precision. </p>
