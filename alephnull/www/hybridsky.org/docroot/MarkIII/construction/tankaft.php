          <td valign="top"><h4>Injectors</h4>
            <ul>
              <li>The injector is made by drilling holes in the brass caps. </li>
              <li>Drill 6 holes in this injector. Each hole is drilled with a 1/16&quot; drill bit. The holes should all lie on a 3/8&quot; diameter circle about the center of the injector. All should be drilled at a 15-degree angle, impinging about a common point. This step requires a drill press or a very steady hand. Much of the performance of the motor comes from having a precise injector. </li>
              <li>Convergence can be testing by using compressed air to force water through the injectors and verifying the streams impinge. </li>
