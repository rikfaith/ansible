    <td><h3>Notes on Gluing PVC Pipe </h3>
      <a name="Glue" id="Glue"></a>
      <p>First, some notes on gluing PVC pipe. In the past we've had  trouble with PVC rocket motors coming apart, usually at glue joints.&nbsp;  We've evolved a system of gluing that has worked well for our uses. Since following these gluing steps we've never had a glue joint fail under normal use:</p>
      <ul>
        <li>Sand any cut pipe ends  until they are smooth.&nbsp; When gluing a piece of pipe into a coupler or  bushing the dry pipe should slide easily and without force about  half-way into the joint.</li>
        <li>Make sure you have a  piece or two of clean paper towel easy to reach when gluing<br />
        </li>
        <li>Clean each piece to be  glued with the PVC pipe cleaning solution.&nbsp; (Yellow-label on the can.)&nbsp;  Visually inspect to ensure the pipe and socket are free of dirt and  debris.</li>
        <li>Coat each surface to be  glued with PVC primer.&nbsp; (Purple liquid in can with purple label.)&nbsp;  Allow to dry perhaps 10 seconds.</li>
        <li>Working quickly but  without rushing, coat the pipe-end with a light layer of <em><strong>heavy-duty</strong></em> PVC  pipe glue.&nbsp; Coat the inside of the socket with a similar layer.&nbsp; Re-coat  the pipe.</li>
        <li>Push the pipe quickly  and firmly with a slight twisting motion into the socket.&nbsp; Hold the  pipe into the socket for 30 seconds. If you don't hold it for a full 30  seconds it may well pop back out.</li>
        <li>While you are holding  the joint together wipe up excess glue with the paper towel.</li>
        <li><strong>Finally, and most importantly</strong>, do not trust any glue joint to hold pressure until it has cured at least 24 hours <em>and no longer smells of PVC solvents. </em></li>
      </ul>
