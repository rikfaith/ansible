    <td><h3>Plumbing Stack </h3>
      <p>All parts are described with words and McMaster-Carr part numbers.</p>
      <h4>Notes:</h4>
      <p>One of the goals of the Mark-III PVC motor project was to build a reasonably large hybrid without a machine shop. Unfortunately the plumbing assembly uses a custom-made quick-disconnect fitting, which we had a friend machine in his shop.</p>
      <p>The quick-disconnect fitting is described <a href="../../p1/motor/quickdisconnect.php">here</a>. </p>
      <h4>Overview</h4>
      <p>The tank needs three connections to the outside: fill, dump, and vent. Fill and dump need to connect to the bottom of the tank, while vent connects to the top.</p>
      <p>Since there is only one port into the tank,a pair of T fittings are used to split out connections to the three valves. The exact layout of all of this is unimportant. The only slightly subtle part is the dip tube, which is connected to the top of the larger T fitting using a tube compression fitting that has been drilled out to allow the dip tube to pass through. The dip tube passes through the compression fitting and runs all the way to the aft end of the tank. </p>
      <p>There is no need to build out the rest of the stack exactly as shown. This was optimized at least in part around the brass bits we had on hand. </p>
      <p>On the other hand, getting the brass right, so that it fits into a 4&quot; body tube and lines up on the ports in the tube is the hardest part of building this motor. </p>
