    <td width="768"><h3>Mark-IIId Flight Test 1, November 10, 2007 </h3>
        <p>This is the short version of the launch report.  I may write up more details later.</p>
      <p>After several delays we launched at 2:00 PM Saturday.  The rocket flew to about 1700' on our Mark-IIId hybrid motor.  Unfortunately only one parachute deployed.  The other tangled in the rigging.  The resulting landing was hard enough to cause extensive damage.  The motor, aft two sections of air-frame, and the Walston transmitter were all damaged or destroyed by the landing.</p>
      <h4>Things that worked well:</h4>
      <ul>
          <li> Launch control system</li>
        <li>Nitrous plumbing, including the quick-disconnect fitting that Mike machined for us</li>
        <li>Nitrous cooling system</li>
        <li>Nitrous ignition</li>
        <li>Flight was stable despite low thrust and a 30:1 length/diameter ratio.<br />
          </li>
      </ul>
      <p> The motor worked perfectly, except that it underperformed substantially.   There were no leaks, the PVC chamber and nozzle survived the 3.5 second burn intact.  However achieving an altitude of 1700 feet rather than the simulated 4000 feet suggests the we got at most 60% of the expected thrust from the rocket.</p>
      <h4>Things that did not work:</h4>
      <ul>
          <li>Parachute rigging tangled</li>
        <li>Nose cone deployed at apogee</li>
        <li>Aft airframe was simply not strong enough to withstand the landing shock of an 8kg rocket.</li>
        <li>Trying to fit both Walston and the telemetry package into the nosecone at the same time.</li>
        <li>The telemetry package stopped working shortly before launch.  Because we were already so delayed we decided to launch with the transmitter turned off, hoping to try again no a later flight.</li>
      </ul>
      <p>We need to understand why the motor underperformed so badly.  We hope to redesign the injector, rebuild the motor and the aft sections of airframe and try again a at the late February launch in Bayboro, NC. </p>
