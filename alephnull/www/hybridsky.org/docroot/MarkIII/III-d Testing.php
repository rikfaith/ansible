            <p>This photo shows the Mark-IIId on the test stand, prepped and ready for the first test firing. </p>
            <p>The nitrous fill line is the white nylon tube running up the left side of the motor. The brown wire that meets it provides current to release the fill line. The white wire that attaches near the bottom controls the dump valve. The ignition wire has not yet been attached.</p>
            <p>The brown wire and the fill line fall away when the quick-disconnect is released. The ignition line falls away when immediately after the ignition sequence begins. And if this were a launch then the white dump control line would pull loose as the rocket ascends. </p></td>
