            <p>In this test the chamber is schedule 40 PVC and the grain is cast acrylic tube. This combination is translucent at the intensity of this test.</p>
            <p>We tested acrylic to reduce the acrid smoke that comes from burning PVC. That worked, but the fuel regression rate was very low, suggesting very low specific impulse and total impulse. Our hypothesis is that clear plastic does not absorbe enough heat to boil off properly. </p></td>
