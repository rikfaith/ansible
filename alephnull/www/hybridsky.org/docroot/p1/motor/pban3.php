    <td><h3>Introduction</h3>
      <p>This page documents the PBAN fuel grains we plan to use for medium scale testing. See test plan <a href="../testing/next.php">here</a>. </p>
      <h4>Links</h4>
      <p>Information on our original PVC fuel grains is <a href="pvcfuel.html">here</a>. </p>
      <p>Obsolete PBAN page is <a href="pbanfuel.php">here</a>. </p>
      <h3>Design </h3>
      <p>The PBAN grains are cast into a section of 3&quot; PVC pipe. This piece of pipe serves as the casting tube and as the chamber liner. PVC is cheap and durable enough for this purpose. </p>
      <p>When we get to full scale runs we will probably shift to phenolic liners and tubes to get complete use of the full diameter of the chamber. </p>
      <p>The initial design calls for using a 1-1/2&quot; PVC pipe as the mandrel. This gives a web thickness of 0.57&quot;. (Web OD will be a nominal 3.042&quot;, ID nominal 1.900&quot;.) Note, however that we wrap the mandrel in plastic film, increasing the ID by an estimated 0.010&quot;. </p>
      <p> We cast into the PVC pipe by plugging the bottom end with a cast epoxy plug that performs 3 functions. It seals the end, it centers the mandrel, and it ensures that the PVC pipe is about 0.75&quot; longer than the PBAN grain at each end. The mandrel is center at the top using a 3&quot; couple and 3&quot; to 1-1/2&quot; bushing. This top cap is trimmed with a Dremel sander so that the bushing slides all the way over the mandrel.</p>
      <p>The mandrel is wrapped in about 2 layers of heavy self-adheasive plastic film. We use film purchased from U-Haul, sold as a moving wrap to keep awkward objects fastened down. </p>
      <p>The epoxy rings were cast using 24g resin, 8g medium-cure hardner, 2g phenolic micro-balloons, and 0.1g fused silica. The additives were put in to reduce the viscosity of the uncured mix in order to make it easier to cast. </p>
      <p>The fuel grains will be 7.5&quot; long, centered inside the 9&quot; long tube. The 3/4&quot; gap  at each end ensures good mixing of the fuel and oxidizer for a more complete burn. </p>
      <h4>Advantages of this design:</h4>
      <ul>
        <li>Inexpensive.</li>
        <li>Rugged.</li>
      </ul>
      <h4>Disadvantages:</h4>
      <ul>
        <li>Wastes a fair amount of space. The PVC pipe is both too thick and its O.D. is not quite big enough. </li>
      </ul>
      <h4>Formula</h4>
      <p>Based on reading <em>Experimental Composite Propellant</em> by Terry W. McCreary, Ph.D., we are planning on using the following formula for our PBAN fuel grains:</p>
      <ul>
        <li>81.2% PBAN</li>
        <li>17.8% DER-331 (an Epoxy resin)</li>
        <li>1.0% carbon black</li>
      </ul>
      <p>We will also add about 1 drop of silicone oil (PDMS) per kg of mix as an anti-foaming agent.</p>
      <p>In concrete terms, we will use</p>
      <ul>
        <li>1,380g PBAN</li>
        <li>&nbsp;303g DER-331</li>
        <li>&nbsp;&nbsp;17g Carbon black  </li>
        <li> 10 drops of silicon oil </li>
      </ul>
      <p>We expect a small (135g) amount of leftovers. </p>
      <h3>Construction</h3>
      <h4>Notes</h4>
      <ul>
        <li>Mixed and then degassed to 29.25 inches. Volume of the mix still expands to the top of the bowl (extimated 2x) at 28.5 inches. </li>
      </ul>      <h4>Results</h4>
      <ul>
        <li>This formula produces a sticky black rubber that is not very strong.</li>
        <li>A small mount leaks at the bottom during curing. We should work to add more grease to the bottom of the 3-1/2&quot; PVC to make this extra easier to remove.</li>
        <li>Using plastic film makes it easy to get the mandrel out. Getting the plastic film out is a little more challenging. Should grease the outside of the film to aid in this process. </li>
      </ul>
      <p>This page documents the grains used in tests 12 and 13, on May 25. </p></td>
