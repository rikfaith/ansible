    <td><h3>Introduction</h3>
      <p>This page documents the PBAN fuel grains we use.</p>
      <p>Information on our original PVC fuel grains is <a href="pvcfuel.html">here</a>. </p>
      <h3>Design </h3>
      <p>The PBAN fuel grains are built in two steps. First we create the liner. We start with the desired length of PML phenolic tube. We cut a slit length wise on one side and then glue the liner back together. This reduces the diameter from x.xx&quot; to x.xx&quot; so it will fit in our motor.</p>
      <p>The second step is to cast PBAN into the liner using a wax coated wooden rod as mandrel to form the core. The PBAN is mixed with 1% carbon-black by weight to improve regression during burn. </p>
      <h4>Advantages of this design:</h4>
      <ul>
        <li>The liner and casting tube are one and the same, reducing the number of custom-made tubes we need. We also get a liner that is guaranteed to support the pressure of the injector bulkhead. </li>
      </ul>
      <h4>Disadvantages:</h4>
      <ul>
        <li>Relatively expensive, both in $$ and labor.</li>
      </ul>
