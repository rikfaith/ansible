      <h3>Summary of Results</h3>
      <p>We conducted 3 tests. All of them failed to ignite. However, we believe we've learned a lot about the conditions that cause the ignition grain to go out. </p>
      <h3><a name="Plan" id="Plan"></a>Test Plan</h3>
      <p>Goals for this test:</p>
      <ul>
        <li>Achieve successful ignition </li>
        <li>Measure the thermal load on the motor casing during a short run.</li>
        <li>Measure chamber pressure and match against simulations.</li>
      </ul>
      <p>This is the same basic plan as <a href="080329.php">test one</a>. However we are tinkering with the pyrovalve design hoping that fixes our ignition problems.</p>
      <p>We expect to test ignition using the 12&quot; long fuel grain (short burt). We have 2 modified versions, small and large. (Details below.) Ignition tests will proceed in this order:</p>
      <ul>
        <li>Large pyrovalve, 3&quot; PVC fuel grain (same as test 1).</li>
        <li></li>
        Small pyrovalve, 1-1/2&quot; PVC fuel grain. 
      </ul>
      <p>Based on the results of those two tests, we'll decide what next. We will go to the site with 2 of each type of pyrovalve and 4 fuel grains, 1 of each type and size. </p>
      <h3><a name="Pretest" id="Pretest"></a>Pretest Work</h3>
      <h4>Machining:  </h4>
      <ul>
        <li>Mike Harris shaved another 2 mils of the O.D. of the nozzle collar.</li>
        <li>About 12 mils off the O.D. of the collar at the bottom of the O-ring groves.</li>
        <li>About 10 mils of the O.D. of the retaining washer.</li>
      </ul>      
      <p>These changes will make the motor much easier to put together and take appart.</p>
      <h4>Large Pryovalves</h4>
      <p>Two new pyrovalve blanks. I ran out of glass fiber, so the receipe was revised:</p>
      <ul>
        <li>120g of Mr. Fiberglass Medium Cure</li>
        <li>12g of 1/32&quot; milled glass fibers</li>
      </ul>      
      <p>Cast in the same mold ring. Used a stepped mandrel made out of 3/4&quot; PVC pipe nested inside 1&quot; PVC pipe. This gives us a region about 0.2&quot; thick where the hole is about 1.0&quot; dia. The rest of the mandrel is about 1.3&quot; dia.</p>
      <p>One was vacuum degassed before pouring, the other after. After works better. </p>
      <p>These blanks came out noticeably thinner than the old blanks. Does the missing 28g of milled glass really take up that much room?</p>
      <h4>Small Pyrovalves</h4>
      <p>I chipped out most of the unburnt pyro compound from the old blanks.</p>
      <h4>Valve Prep</h4>
      <p> I scored the inside of the hole with a chisel and some rough sand paper.</p>
      <p>We recovered the old formula for pyrovalve compound. However, since I'm out of milled glass I dropped that. The mix I used was:</p>
    <ul>
      <li>42 g milled KN</li>
      <li>42 g unmilled KN</li>
      <li>6 g RIO</li>
      <li>30 g medium cure epoxy</li>
      <li>6 g milled glass fibers (<em>omitted</em>)   </li>
      </ul>
    <p>This proved to be more mixture than needed. Probably could have scaled this by 5/6.</p>
    <p>Inside holes in the blanks were coated in a thin layer of epoxy prior to casting. </p>
    <p>Pyrovalves were cast the evening of 4/10/08. </p>
    <p>Two of the valves (one of each type) had some noticeable voids on the surface that mates with the injector face. These were filled by making up 20g of pyro compound and filling the voids using the new batch and a putty knife. </p>
